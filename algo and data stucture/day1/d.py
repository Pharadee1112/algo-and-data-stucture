"""
Approach: Generate + Sort
1. Generate N numbers:
   - x = q % M - M // 2
   - next q = q * 16807 % 2147483647

2. Sort x from small to large.

3. Answer is x[k - 1] (k starts from 1, list starts from 0).

Sort used: Python built-in sort (Timsort), O(N log N), stable.

Complexity:
- Generate:     O(N)
- Sort:         O(N log N)
- Get answer:   O(1)
- Total time:   O(N log N)
- Memory:       O(N)
"""
# "ในเลขทั้งหมดนั้น ตัวที่เล็กเป็นอันดับ k คือเลขอะไร?" จากที่เราเก็บ N ตัว

N, M, q0, k = map(int, input().split())

x = []

q = q0
for i in range(N):
    x.append(q % M - M // 2)
    q = q * 16807 % 2147483647

x.sort()
print(x[k - 1]) # “print the number that is k-th smallest”.
